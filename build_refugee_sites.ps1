<#
  build_refugee_sites.ps1
  ------------------------------------------------------------------
  Reads the UNHCR Verified Refugee Sites CSV (Africa-wide), filters to
  Ethiopia, and writes a small JS layer consumed by the site-level flow map.

  NOTE: these are UNHCR REFUGEE sites (people who fled INTO Ethiopia from other
  countries) - a different population from the IDP (internally displaced) flows
  on the map. They are shown only as reference point locations (no population
  figures are provided in the source).

  Input : unhcr_africa_refugee_sites_*.csv   (in project root)
  Output: data/eth_refugee_sites.js  (window.UNHCR_SITES)
#>
$ErrorActionPreference='Stop'
$root=Split-Path -Parent $MyInvocation.MyCommand.Path
$dataDir=Join-Path $root 'data'; if(-not(Test-Path $dataDir)){New-Item -ItemType Directory $dataDir|Out-Null}

$csv=Get-ChildItem $root -Filter 'unhcr*refugee*sites*.csv' | Sort-Object LastWriteTime -Descending | Select-Object -First 1
if(-not $csv){ throw "No UNHCR refugee sites CSV found in $root" }
Write-Host "Reading $($csv.Name)"

$eth = Import-Csv $csv.FullName | Where-Object { $_.ISO3 -eq 'ETH' -and $_.Latitude -and $_.Longitude } |
  ForEach-Object {
    [ordered]@{
      name   = $_.Site
      lat    = [double]$_.Latitude
      lon    = [double]$_.Longitude
      code   = $_.'Site code'
      source = $_.Source
      updated= $_.Updated
    }
  }
Write-Host ("Ethiopia refugee sites: {0}" -f $eth.Count)

$meta = [ordered]@{
  layer   = 'UNHCR Verified Refugee Sites'
  country = 'Ethiopia'
  note    = 'Refugee sites (people who fled into Ethiopia from other countries) - distinct from IDP flows. Point locations only; no population figures.'
  source  = "UNHCR ($($csv.BaseName))"
  count   = $eth.Count
}
$payload = [ordered]@{ meta=$meta; sites=@($eth) }
$compact = $payload | ConvertTo-Json -Depth 5 -Compress
$js = "/* UNHCR Verified Refugee Sites (Ethiopia) - generated by build_refugee_sites.ps1.`r`n   Refugee camps (cross-border), reference layer only - NOT the IDP flow data. */`r`nwindow.UNHCR_SITES = $compact;`r`n"
$js | Out-File (Join-Path $dataDir 'eth_refugee_sites.js') -Encoding utf8
$payload | ConvertTo-Json -Depth 5 | Out-File (Join-Path $dataDir 'eth_refugee_sites.json') -Encoding utf8
Write-Host "Wrote data/eth_refugee_sites.js"
